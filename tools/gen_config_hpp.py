#!/usr/bin/env python3
"""Emit include/kp/config_gen.hpp: every plain constant in the reference config.py, mechanically.

    KP_REF=ref/current python tools/gen_config_hpp.py > include/kp/config_gen.hpp

WHY GENERATED. config.hpp was hand-lifted, and on the 2026-09-23 re-baseline the one constant that
had drifted (QUOTE_TIER_COUNTS, three rungs -> one) broke two suites. Hand-lifting ~100 constants for
the rest of the live path would be ~100 more chances to do that. Names config.hpp already defines are
SKIPPED, so the hand-written ones (with their reasoning) stay the source for those; everything else
comes from here, and the `config_fresh` test fails if this file no longer matches the reference.

WHAT IS LEFT OUT, deliberately:
  - secrets (KALSHI_KEY_ID, MASSIVE_API_KEY, KALSHI_PRIVATE_KEY_PATH): read at runtime from the
    .env files under KALSHI_ROOT, exactly as config.py does. A secret baked into a header ends up in
    every binary and every core dump.
  - paths (ROOT, DATA_DIR, ...): derived from KALSHI_ROOT at runtime, see kp::config::paths.
  - None-valued knobs: emitted as `<NAME>_IS_NONE = true` so a reader cannot mistake absent for 0.

Every double is written as a C++ hex-float literal, so the value is the bit pattern Python holds.
"""
import os, pathlib, re, sys

# Default: a sibling checkout of the Kalshi repo next to this one (override with KP_REF).
REF = pathlib.Path(os.environ.get("KP_REF", pathlib.Path(__file__).resolve().parents[2] / "Kalshi")).resolve()
sys.path.insert(0, str(REF))
import config  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent.parent
SECRET = {"KALSHI_KEY_ID", "MASSIVE_API_KEY", "KALSHI_PRIVATE_KEY_PATH"}


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lit(v):
    if isinstance(v, bool):
        return "bool", "true" if v else "false"
    if isinstance(v, int):
        return "long", str(v)
    if isinstance(v, float):
        return "double", v.hex() if v == v else "std::numeric_limits<double>::quiet_NaN()"
    if isinstance(v, str):
        return "std::string_view", cstr(v)
    return None


def main():
    hand = set(re.findall(r"inline constexpr [^=;]*?\b([A-Z][A-Z0-9_]+)\s*=",
                          (HERE / "include/kp/config.hpp").read_text()))
    out = ["// GENERATED by tools/gen_config_hpp.py from the reference config.py -- DO NOT EDIT.",
           f"// source sha256: {__import__('hashlib').sha256((REF / 'config.py').read_bytes()).hexdigest()[:16]}",
           "// Hand-written constants (with their reasoning) live in config.hpp and are skipped here.",
           "#pragma once", "#include <array>", "#include <limits>", "#include <string_view>", "",
           "namespace kp::config {", ""]
    skipped = []
    for k in sorted(vars(config)):
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", k) or k in hand or k in SECRET:
            continue
        v = getattr(config, k)
        if v is None:
            if f"{k}_IS_NONE" in hand:
                continue
            out.append(f"inline constexpr bool {k}_IS_NONE = true;")
            continue
        one = lit(v)
        if one:
            out.append(f"inline constexpr {one[0]} {k} = {one[1]};")
            continue
        if isinstance(v, tuple) and v and all(lit(x) and type(x) is type(v[0]) for x in v):
            t = lit(v[0])[0]
            out.append(f"inline constexpr std::array<{t}, {len(v)}> {k} = {{"
                       + ", ".join(lit(x)[1] for x in v) + "};")
            continue
        skipped.append(f"{k} ({type(v).__name__})")
    out += ["", "}  // namespace kp::config", ""]
    out.insert(3, "// Not emitted (non-scalar; hand-ported where the live path needs them): "
               + ", ".join(skipped))
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
